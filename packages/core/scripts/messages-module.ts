// --- src/messages-ja.ts from mdsig/messages_ja.json

export interface CatalogEntry {
  en: string;
  ja: string;
}

export function checkCatalog(entries: unknown): CatalogEntry[] {
  if (!Array.isArray(entries)) throw new Error("messages_ja.json: not an array");
  return entries.map((x, i) => {
    if (x === null || typeof x !== "object" || typeof x.en !== "string" || typeof x.ja !== "string" || Object.keys(x).length !== 2) throw new Error(`messages_ja.json[${i}]: expected {"en", "ja"}`);
    if (!x.en.startsWith("^") || !x.en.endsWith("$")) throw new Error(`messages_ja.json[${i}]: pattern is not anchored: ${x.en}`);
    const groups = new RegExp(`${x.en}|`).exec("")!.length - 1;
    for (const m of x.ja.matchAll(/\{(\d+)(?::msg)?\}/g)) if (Number(m[1]) < 1 || Number(m[1]) > groups) throw new Error(`messages_ja.json[${i}]: {${m[1]}} has no capture group`);
    return { en: x.en, ja: x.ja };
  });
}

export function renderMessagesModule(json: string): string {
  const entries = checkCatalog(JSON.parse(json));
  return `// GENERATED by scripts/gen-messages.ts from mdsig/messages_ja.json. Do not edit by hand.

export const MESSAGES_JA: readonly (readonly [string, string])[] = [
${entries.map((e) => `  [${JSON.stringify(e.en)}, ${JSON.stringify(e.ja)}],`).join("\n")}
];
`;
}
