import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { X509Certificate } from "node:crypto";

const dir = new URL("../tsa-roots/", import.meta.url);
const rows = readdirSync(dir)
  .filter((f) => f.endsWith(".pem"))
  .sort()
  .map((f) => {
    const c = new X509Certificate(readFileSync(new URL(f, dir)));
    if (c.subject !== c.issuer) throw new Error(`${f}: not a self-issued root`);
    const name = /^CN=(.+)$/m.exec(c.subject)![1]!;
    const ou = /^OU=(.+)$/m.exec(c.subject)?.[1];
    return { name: name === "GlobalSign" && ou ? ou : name, sha256: c.fingerprint256.replace(/:/g, "").toLowerCase(), notAfter: new Date(c.validTo).toISOString().slice(0, 10), b64: c.raw.toString("base64") };
  });

const out = `// GENERATED by scripts/gen-tsa-roots.ts from tsa-roots/*.pem. Do not edit by hand.
import { fromBase64 } from "./encoding.ts";

export interface TsaRoot {
  name: string;
  sha256: string;
  notAfter: string;
  der: Uint8Array;
}

const root = (name: string, sha256: string, notAfter: string, b64: string): TsaRoot => ({ name, sha256, notAfter, der: fromBase64(b64) });

// root certificates of public time-stamping services; pass \`tsaRoots\` to use another set
export const DEFAULT_TSA_ROOTS: TsaRoot[] = [
${rows.map((r) => `  root(${JSON.stringify(r.name)}, "${r.sha256}", "${r.notAfter}", "${r.b64}"),`).join("\n")}
];
`;
writeFileSync(new URL("../src/tsa-roots.ts", import.meta.url), out);

// the playground reads this list at start-up, so a new list reaches the page without a core rebuild
const json = { source: "packages/core/tsa-roots/*.pem (npm run build:tsa-roots)", roots: rows.map((r) => ({ name: r.name, sha256: r.sha256, notAfter: r.notAfter, der: r.b64 })) };
writeFileSync(new URL("../../../docs/tsa-roots.json", import.meta.url), JSON.stringify(json, null, 2) + "\n");
console.log(rows.map((r) => `${r.sha256}  ${r.notAfter}  ${r.name}`).join("\n"));
